export function describeKorpayCode(code: string | undefined | null, fallbackMessage?: string): string {
  if (!code) return fallbackMessage?.trim() || '결제 처리 중 오류가 발생했습니다.';
  const known = AUTH_ERRORS[code] ?? APPROVAL_ERRORS[code];
  if (known) return known;
  // 코페이가 준 메시지가 있으면 그걸 쓰고, 없으면 코드라도 남긴다.
  return fallbackMessage?.trim() || `결제에 실패했습니다. (코드 ${code})`;
}

export function isUserCancellation(code: string | undefined | null): boolean {
  return code === KORPAY_USER_CANCELLED;
}
